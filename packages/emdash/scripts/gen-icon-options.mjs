/**
 * Generate src/icon-options.ts from @getvitops/utils' semantic icon map.
 *
 * Generated rather than imported because @getvitops/emdash deliberately carries
 * NO runtime @getvitops/* dependency — that independence is what lets it version
 * separately from the fixed core/generator/utils/cli/vite/astro group (see the
 * root AGENTS.md). A build-time copy keeps the list without the coupling;
 * blocks.test.ts asserts the copy still matches the source, so drift is caught
 * rather than assumed.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { iconMap } from '@getvitops/utils';

const names = Object.keys(iconMap.fa7).sort();
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'icon-options.ts');

const body = `/**
 * Semantic icon names, as Block Kit combobox options.
 *
 * GENERATED by scripts/gen-icon-options.mjs — do not edit by hand.
 *
 * A copy rather than an import: this package carries no runtime @getvitops/*
 * dependency, which is what lets it version independently of the fixed
 * toolchain group. blocks.test.ts checks the copy against the real map.
 */
export const SEMANTIC_ICON_OPTIONS: { label: string; value: string }[] = [
${names.map((n) => `  { label: '${n}', value: '${n}' },`).join('\n')}
];
`;

writeFileSync(out, body);
console.log(`✓ icon-options.ts — ${names.length} semantic names`);
